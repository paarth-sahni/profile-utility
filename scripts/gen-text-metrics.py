#!/usr/bin/env python3
"""
Purpose: writes lib/textMetrics.data.ts, the advance widths of Lexend Light (public/fonts/LexendLight-regular.ttf) for the
characters a profile uses (Latin, Latin-1, Latin Extended-A/B, general punctuation, currency signs), in 1/1000 em. Used by
lib/textMetrics.ts to estimate how many lines a description takes in the PDF (page-break units, scripts/patch-templates.py).
Needs fontTools (pip install fonttools). Run: python3 scripts/gen-text-metrics.py
"""
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
font = TTFont(ROOT / "public" / "fonts" / "LexendLight-regular.ttf")
assert font["head"].unitsPerEm == 1000
cmap, hmtx = font.getBestCmap(), font["hmtx"].metrics
ranges = [(0x20, 0x24F), (0x2000, 0x206F), (0x20A0, 0x20CF)]
widths = {cp: hmtx[cmap[cp]][0] for lo, hi in ranges for cp in range(lo, hi + 1) if cp in cmap}
# compact: "<code point hex>:<width hex>" pairs
body = ",".join(f"{cp:x}:{w:x}" for cp, w in sorted(widths.items()))
out = ROOT / "lib" / "textMetrics.data.ts"
out.write_text(
    "// Generated by scripts/gen-text-metrics.py from public/fonts/LexendLight-regular.ttf: do not edit.\n"
    "// Advance widths in 1/1000 em as \"<code point hex>:<width hex>\" pairs.\n"
    f'export const LEXEND_LIGHT_WIDTHS = "{body}";\n'
)
print(f"wrote {out.relative_to(ROOT)} ({len(widths)} characters)")
